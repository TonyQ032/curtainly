/** Text stored in `companies.notes`: ticketing, usual venues and research notes. */
export function seedNotes(c: SeedCompany): string {
  const t = c.ticketing;
  const ticketing = [
    `Ticketing: ${TICKETING_LABELS[t.platform]}`,
    t.url ? ` (${t.url})` : '',
    t.unverified ? ', unverified' : '',
    '.',
  ].join('');
  const parts = [c.notes, ticketing];
  if (c.venues.length) parts.push(`Venues: ${c.venues.join('; ')}.`);
  parts.push(`City: ${c.city}.`);
  return parts.filter(Boolean).join('\n');
}
